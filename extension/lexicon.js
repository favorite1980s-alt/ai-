function mesLookup(word, user = {}) {
  if (typeof word !== "string") return null;
  const key = word.toLowerCase().replace(/[’]/g, "'").replace(/^[^a-z]+|[^a-z']+$/g, "");
  if (!key) return null;
  const keys = [key];
  if (key.endsWith("'s")) keys.push(key.slice(0,-2));
  if (key.endsWith("ies")) keys.push(key.slice(0,-3)+"y");
  if (key.endsWith("ing")) { keys.push(key.slice(0,-3),key.slice(0,-3)+"e"); }
  if (key.endsWith("ed")) { keys.push(key.slice(0,-2),key.slice(0,-1)); }
  if (key.endsWith("es")) keys.push(key.slice(0,-2));
  if (key.endsWith("s")) keys.push(key.slice(0,-1));
  for (const candidate of keys) {
    if (Object.prototype.hasOwnProperty.call(user,candidate)) return String(user[candidate]);
    if (Object.prototype.hasOwnProperty.call(MES_GLOSSES,candidate)) return MES_GLOSSES[candidate];
  }
  return null;
}
